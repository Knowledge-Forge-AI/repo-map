"""Real filesystem classification parity through discovery, sealing and refusal."""

from __future__ import annotations

import hashlib
from pathlib import Path

import pytest

from common_lore_index.artifacts._sealing_meter import SealingMeter
from common_lore_index.artifacts.sealing_governance import SealingBudget, SealingBudgetExceeded
from common_lore_index.graph._metered_discovery import MeteredDiscoveryHooks
from common_lore_index.graph.discovery import discover_repository
from repomap_test_support.sealing_governance_fixtures import (
    binding_for, graph_for, open_descriptor_count, seal, write_tree,
)


CASES = (
    ("script", b"#!/usr/bin/env python3\nprint('fixture')\n", "python", False),
    ("script.sh", b"#!/bin/zsh\r\necho fixture\n", "zsh", False),
    (".profile", b"export FIXTURE=1\n", "unknown", False),
    ("script", b" " * 5000 + b"#!/bin/zsh\n", "zsh", False),
    ("script", b"x" * 9000 + b"\n\xff", "unknown", False),
    ("plain.go", b"package fixture\n" * 50, "go", False),
    ("generated.go", b"// Code generated by fixture. DO NOT EDIT.\npackage fixture\n", "go", True),
    ("late.go", b"package fixture\n" * 39 + b"// Code generated by fixture. DO NOT EDIT.\n", "go", False),
    ("broken.go", b"package fixture\n\xff\n// Code generated by fixture. DO NOT EDIT.\n", "go", False),
    ("completion", b"  \t_arguments '-x'\n", "zsh", False),
    ("completion", b"echo\xe2\x80\xa8#compdef fixture\n", "zsh", False),
    ("completion", b"echo\xc2\x85  _arguments\n", "zsh", False),
    ("completion", b"#compde\nf\n", "unknown", False),
    ("completion", b"#compdef fixture\n\xff", "unknown", False),
    ("completion", b"#comp\xc3", "unknown", False),
    ("functions/_fixture", b"\xff", "zsh", False),
)


@pytest.mark.parametrize("governed", (False, True), ids=("observe", "governed"))
@pytest.mark.parametrize(("relative", "body", "language", "generated"), CASES,
                         ids=[f"corpus-{i}" for i in range(len(CASES))])
def test_real_classification_and_sealed_identity_match_incumbent(
    tmp_path: Path, relative: str, body: bytes, language: str, generated: bool, governed: bool,
) -> None:
    source = write_tree(tmp_path / "source", {relative: body})
    graph = graph_for(binding_for("entry", source))
    before = open_descriptor_count()
    expected = discover_repository(source)
    assert len(expected) == 1
    assert (expected[0].language, expected[0].generated) == (language, generated)
    assert expected[0].content_hash == hashlib.sha256(body).hexdigest()
    baseline = seal(graph, tmp_path / "baseline")

    budget = SealingBudget(max_read_bytes=100 * len(body) + 2**20) if governed else None
    discovery_meter = SealingMeter(budget, governed=governed)
    actual = discover_repository(source, io_hooks=MeteredDiscoveryHooks(discovery_meter))
    assert actual == expected
    assert discovery_meter.snapshot().reader("discovery") == len(body)

    meter = SealingMeter(budget, governed=governed)
    sealed = seal(graph, tmp_path / "observed", io_meter=meter)
    assert (sealed[0], sealed[2]) == (baseline[0], baseline[2])
    assert meter.snapshot().read_bytes > 0 and meter.snapshot().refused_limit is None
    if budget is not None:
        assert budget.max_read_bytes is not None
        assert meter.snapshot().read_bytes <= budget.max_read_bytes
    assert not list((tmp_path / "observed" / "temporary").iterdir())
    assert (source / relative).read_bytes() == body
    assert open_descriptor_count() == before


def _stored_files(root: Path) -> dict[str, tuple[bytes, int]]:
    return {p.relative_to(root).as_posix(): (p.read_bytes(), p.stat().st_mode)
            for p in root.rglob("*") if p.is_file()}


@pytest.mark.parametrize(("relative", "body"), (
    ("long.sh", b"#!" + b"a" * (2**20) + b"\n"),
    ("wide.go", (b"// Code generated by fixture. DO NOT EDIT." + b" " * 40_000 + b"\n") * 30),
), ids=("shebang-retention", "combined-go-retention"))
def test_classification_retention_refusal_preserves_accepted_store(
    tmp_path: Path, relative: str, body: bytes,
) -> None:
    source = write_tree(tmp_path / "source", {relative: body})
    graph = graph_for(binding_for("entry", source))
    store = tmp_path / "store"
    accepted = seal(graph, store)
    before_files = _stored_files(store)
    before_fds = open_descriptor_count()
    meter = SealingMeter(SealingBudget(max_read_bytes=100 * len(body)), governed=True)
    with pytest.raises(SealingBudgetExceeded, match="classification_retention"):
        seal(graph, store, io_meter=meter)
    assert meter.snapshot().refused_limit == "classification_retention"
    assert meter.snapshot().write_bytes == 0
    assert _stored_files(store) == before_files
    assert open_descriptor_count() == before_fds
    assert not list((store / "temporary").iterdir())
    assert seal(graph, store)[0] == accepted[0]
