def _build_spec_in_root(root: Path, name: str = "home"):
    home = root / name
    home.mkdir(mode=0o700, exist_ok=True)
    setup_local_runtime(home)
    cfg = home / "repomap.rpl.toml"
    cfg.write_text(cfg.read_text().replace("[runtime]", '[runtime]\ncoordinator_mode = "native"'))
    return build_service_package_spec(home)


def test_platforms_and_systemd_adapter_contract_matrix(tmp_path: Path) -> None:
    """Platform selection and systemd unit rendering/decoding enforce strict syntax and metadata rules."""
    with pytest.raises(ValueError, match="service_user_home_invalid"):
        select_service_adapter("linux", user_home=cast(Any, "relative/home"), uid=1000)
    with pytest.raises(ValueError, match="service_user_identity_invalid"):
        select_service_adapter("linux", user_home=tmp_path, uid=cast(Any, True))
    assert isinstance(select_service_adapter("darwin", user_home=tmp_path, uid=501), LaunchdUserAdapter)
    assert isinstance(select_service_adapter("linux", user_home=tmp_path, uid=1000), SystemdUserAdapter)
    with pytest.raises(NativeServiceUnavailable, match="native_service_adapter_pending_windows"):
        select_service_adapter("win32", user_home=tmp_path, uid=1000)
    with pytest.raises(NativeServiceUnavailable, match="native_service_manager_unsupported"):
        select_service_adapter("freebsd", user_home=tmp_path, uid=1000)

    with controlled_service_authority(tmp_path / "exec-auth"):
        spec = _build_spec_in_root(tmp_path)
        adapter = SystemdUserAdapter(user_home=tmp_path / "user", uid=1000)
        rendered = adapter.render(spec)
        assert adapter.recognizes(rendered) is True
        text = rendered.decode("utf-8")

        # recognizes failure branches
        assert adapter.recognizes(cast(Any, "not-bytes")) is False
        assert adapter.recognizes(text.replace("# Generated by RepoMap service package v1\n", "", 1).encode("utf-8")) is False
        assert adapter.recognizes(text.replace("X-RepoMap-Service-Identity=org.repomap.coordinator\n", "", 1).encode("utf-8")) is False
        assert adapter.recognizes(text.replace("X-RepoMap-Service-Package=1\n", "", 1).encode("utf-8")) is False
        assert adapter.recognizes((text + "Environment=FOO=1\n").encode("utf-8")) is False
        bad_argv_text = text.replace('"--json"', '"--not-json"')
        assert adapter.recognizes(bad_argv_text.encode("utf-8")) is False

        # decode_systemd_exec_argv & quoting/decoding helpers
        with pytest.raises(ValueError, match="service_definition_invalid"):
            decode_systemd_exec_argv(b"x" * (_MAX_DEFINITION_BYTES + 1))
        for bad_exec in (
            b"ExecStart=unquoted\n",
            b'ExecStart=prefix "a" "b"\n',
            b'ExecStart="a" suffix\n',
        ):
            with pytest.raises(ValueError, match="service_definition_invalid"):
                decode_systemd_exec_argv(bad_exec)

        with pytest.raises(ValueError, match="service_definition_value_invalid"):
            _quote_systemd_exec_token("bad\nval")
        with pytest.raises(ValueError, match="service_definition_value_invalid"):
            _quote_systemd_scalar("bad\rval")

        assert _decode_systemd_value(r'a\"b\\c$$d%%e') == 'a"b\\c$d%e'
        with pytest.raises(ValueError, match="service_definition_invalid"):
            _decode_systemd_value("trailing\\")
        with pytest.raises(ValueError, match="service_definition_invalid"):
            _decode_systemd_value("single$dollar")

        assert _systemd_recognized_argv(("only_one",), "a" * 64, "b" * 64) is False
        argv_with_nl = (*spec.foreground_argv[:10], "--json\n")
        assert _systemd_recognized_argv(argv_with_nl, spec.python_sha256 or "", spec.psql_sha256 or "") is False

        with pytest.raises(ValueError, match="service_definition_invalid"):
            _metadata_value("NoKey=1\n", "X-RepoMap-Python-SHA256")


def test_launchd_adapter_and_contract_executable_verification(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Launchd plist validation and contract executable verification reject tampered inputs."""
    with controlled_service_authority(tmp_path / "exec-auth"):
        spec1 = _build_spec_in_root(tmp_path, "home1")
        spec2 = _build_spec_in_root(tmp_path, "home2")
        launchd = LaunchdUserAdapter(user_home=tmp_path / "user", uid=501)
        plist_bytes = launchd.render(spec1)
        assert launchd.recognizes(plist_bytes) is True
        with pytest.raises(ValueError, match="service_definition_invalid"):
            launchd.validate(plist_bytes, spec2)

        assert launchd.recognizes(cast(Any, "not-bytes")) is False
        payload = plistlib.loads(plist_bytes)
        assert launchd.recognizes(plistlib.dumps({**payload, "EnvironmentVariables": {}})) is False
        assert launchd.recognizes(plistlib.dumps({**payload, "ProgramArguments": ["bad"]})) is False
        assert launchd.recognizes(plistlib.dumps({**payload, "ExtraKey": "x"})) is False

        assert _launchd_recognized_argv("not-a-list", "a" * 64, "b" * 64) is False
        assert _launchd_recognized_argv(["only-one"], "a" * 64, "b" * 64) is False
        bad_argv = list(spec1.foreground_argv)
        bad_argv[1] = "--bad-flag"
        assert _launchd_recognized_argv(bad_argv, spec1.python_sha256, spec1.psql_sha256) is False

    # contract.py branches
    with pytest.raises(ValueError, match="service_repo_map_home_invalid"):
        _normalize_home("/tmp/bad\x00home")

    monkeypatch.setattr("common_lore_index.service_package.contract.is_approved_python_executable", lambda _p: False)
    with pytest.raises(RuntimeError, match="service_foreground_executable_invalid"):
        build_service_package_spec(tmp_path)

    assert _recognizes_executable_reference(tmp_path / "python3", "not-a-digest") is False
    assert _recognizes_executable_reference(tmp_path / "not_psql", "a" * 64, exact_name="psql") is False

    exec_file = tmp_path / "custom_bin"
    exec_file.write_bytes(b"#!/bin/sh\n")
    exec_file.chmod(0o755)
    assert _recognizes_executable_reference(
        exec_file, "a" * 64, name_pattern=re.compile(r"python3")
    ) is False

    # World-writable executable rejected by _safe_resolved_executable
    writable_exec = tmp_path / "writable_bin"
    writable_exec.write_bytes(b"#!/bin/sh\n")
    writable_exec.chmod(0o777)
    assert _safe_resolved_executable(writable_exec) is None

    # Missing executable reference checks
    missing_py = tmp_path / "python3.12"
    assert _recognizes_executable_reference(
        missing_py, "a" * 64, name_pattern=re.compile(r"python(?:\d+(?:\.\d+)*)?")
    ) is True
    assert _is_missing_executable_reference("relative/bin") is False
    assert _is_missing_executable_reference(exec_file) is False
    assert _is_missing_executable_reference(missing_py, exact_name="psql") is False
    assert _is_missing_executable_reference(missing_py, name_pattern=re.compile(r"ruby")) is False

    # psql resolution branches
    assert is_approved_psql_executable(tmp_path / "not_psql") is False
    monkeypatch.setattr("common_lore_index.service_package.contract.shutil.which", lambda _name: None)
    assert is_approved_psql_executable(tmp_path / "psql") is False
    with pytest.raises(RuntimeError, match="service_psql_unavailable"):
        _resolve_psql_dependency()

    monkeypatch.setattr("common_lore_index.service_package.contract.shutil.which", lambda _name: "relative/psql")
    with pytest.raises(RuntimeError, match="service_psql_unavailable"):
        _resolve_psql_dependency()

    empty_file = tmp_path / "empty_bin"
    empty_file.write_bytes(b"")
    with pytest.raises(RuntimeError, match="service_foreground_executable_invalid"):
        _executable_sha256(empty_file)


def test_owned_artifacts_io_and_locking_safety_boundaries(tmp_path: Path) -> None:
    """Owned artifact operations enforce 0o700 directories, 0o600 files, lock ownership, and rollback."""
    bad_dir = tmp_path / "bad_dir"
    bad_dir.mkdir(mode=0o755)
    with pytest.raises(ServiceArtifactError, match="service_directory_unsafe"):
        ensure_private_directory(bad_dir, owner_uid=999999)

    writable_dir = tmp_path / "writable_dir"
    writable_dir.mkdir(mode=0o700)
    writable_dir.chmod(0o777)
    with pytest.raises(ServiceArtifactError, match="service_directory_unsafe"):
        require_owner_directory(writable_dir)
    with pytest.raises(ServiceArtifactError, match="service_directory_unsafe"):
        _validate_parent(writable_dir, None)

    with pytest.raises(ServiceArtifactError, match="service_definition_unsafe"):
        _absolute_path(Path("relative/unit"))
    with pytest.raises(ServiceArtifactError, match="service_definition_invalid"):
        _validate_new_content(cast(Any, "not-bytes"), lambda _b: True)
    with pytest.raises(ServiceArtifactError, match="service_definition_invalid"):
        _validate_new_content(b"bad", lambda _b: False)

    priv_dir = tmp_path / "priv"
    ensure_private_directory(priv_dir)
    target = priv_dir / "unit.service"

    with pytest.raises(ServiceArtifactError, match="service_definition_missing"):
        replace_owned_artifact(target, b"ok", lambda b: b == b"ok")

    # _remove_owned_artifact_unlocked when file does not exist
    _remove_owned_artifact_unlocked(target, lambda _b: True, None)

    install_owned_artifact(target, b"v1", lambda b: b in {b"v1", b"v2"})
    prior = inspect_owned_artifact(target, lambda b: b in {b"v1", b"v2"})
    assert prior is not None

    # Tamper with content so _require_unchanged_target raises
    target.write_bytes(b"v2")
    with pytest.raises(ServiceArtifactError, match="service_definition_unsafe"):
        _require_unchanged_target(target, prior, lambda b: b in {b"v1", b"v2"}, None)

    # _restore_after_failed_replace with content and None
    _restore_after_failed_replace(target, b"v1")
    assert target.read_bytes() == b"v1"
    _restore_after_failed_replace(target, None)
    assert not target.exists()

    # _remove_linked_target when linked vs unlinked
    tmp_f = priv_dir / "tmp_link"
    tmp_f.write_bytes(b"v1")
    tmp_f.chmod(0o600)
    os.link(tmp_f, target)
    _remove_linked_target(target, tmp_f)
    assert not target.exists()

    other_f = priv_dir / "other"
    other_f.write_bytes(b"v2")
    with pytest.raises(OSError, match="linked target changed"):
        _remove_linked_target(other_f, tmp_f)

    # inspect_owned_artifact with bad mode
    other_f.chmod(0o644)
    with pytest.raises(ServiceArtifactError, match="service_definition_unsafe"):
        inspect_owned_artifact(other_f, lambda _b: True)

    # _mutation_lock with wrong owner_uid
    with pytest.raises(ServiceArtifactError, match="service_mutation_lock_unsafe"):
        with _mutation_lock(target, owner_uid=999999):
            pass
