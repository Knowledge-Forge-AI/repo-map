"""Live classifier delegates, exact pruning objects and suspended-walk custody."""
from contextlib import ExitStack
import pytest
from common_lore_index.graph import _discovery_classify as classification, _capture_discovery as base, discovery
from common_lore_index.graph._capture_control import CaptureControl
from common_lore_index.graph._capture_control_discovery import ControlledCaptureDiscoveryHooks, discover_controlled


class Walk:
    def __init__(self, value):
        self.value = value
        self.closes = 0
        self.used = False

    def __iter__(self):
        return self

    def __next__(self):
        if self.used:
            raise StopIteration
        self.used = True
        return self.value

    def close(self):
        self.closes += 1


def test_walk_yields_exact_mutable_pruning_objects_and_closes_once(tmp_path, monkeypatch):
    value = (str(tmp_path), ["node_modules", "src"], ["public.py"])
    walk = Walk(value)
    monkeypatch.setattr(base.os, "walk", lambda _root: walk)
    with ExitStack() as stack:
        hooks = ControlledCaptureDiscoveryHooks(lambda: None, stack)
        actual = next(iter(hooks.walk(tmp_path)))
        assert actual is value and actual[1] is value[1] and actual[2] is value[2]
        actual[1][:] = ["src"]
    assert value[1] == ["src"] and walk.closes == 1


@pytest.mark.parametrize("origin", ["walk", "classifier"])
def test_walk_release_is_immediate_with_retained_failure_traceback(tmp_path, monkeypatch, origin):
    (tmp_path / "public.py").write_text("VALUE = 1\n")
    walk = Walk((str(tmp_path), [], ["public.py"]))
    failure = ValueError("callback")
    checks = []
    monkeypatch.setattr(base.os, "walk", lambda _root: walk)

    def check():
        checks.append(True)
        if origin == "walk" and len(checks) == 2:
            raise failure

    if origin == "classifier":
        def refuse(_path):
            raise failure
        monkeypatch.setattr(base.CaptureDiscoveryHooks, "content_hash", lambda _self, path: refuse(path))
    with pytest.raises(ValueError) as caught:
        discover_controlled(discovery.discover_repository, tmp_path, (), CaptureControl(check))
    assert caught.value is failure and caught.tb is not None and walk.closes == 1


@pytest.mark.parametrize("name,content", [("public.py", "VALUE=1\n"), ("public", "#!/bin/zsh\necho public\n"), ("generated.go", "// Code generated by fixture. DO NOT EDIT.\npackage public\n")])
def test_controlled_probe_changes_no_classification_or_pruning(tmp_path, name, content):
    (tmp_path / name).write_text(content)
    ignored = tmp_path / "node_modules"
    ignored.mkdir()
    (ignored / "hidden.py").write_text("HIDDEN=1\n")
    ordinary = discovery.discover_repository(tmp_path, io_hooks=base.CaptureDiscoveryHooks())
    controlled = discover_controlled(discovery.discover_repository, tmp_path, (), CaptureControl(lambda: None))
    assert tuple(ordinary) == controlled and len(controlled) == 1


def test_live_reader_delegation_and_probe_not_reimplemented(tmp_path, monkeypatch):
    called = []

    def read(path):
        called.append(path)
        return "live"

    monkeypatch.setattr(classification, "first_line", read)
    monkeypatch.setattr(classification, "is_go_generated_file", lambda _path: True)
    monkeypatch.setattr(classification, "is_zsh_completion_candidate", lambda _path: True)
    monkeypatch.setattr(base.CaptureDiscoveryHooks, "content_hash", lambda _self, _path: "existing-probe")
    with ExitStack() as stack:
        hooks = ControlledCaptureDiscoveryHooks(lambda: None, stack)
        assert hooks.readers() is hooks
        assert hooks.first_line(tmp_path) == "live"
        assert hooks.is_go_generated_file(tmp_path) and hooks.completion(tmp_path)
        assert hooks.content_hash(tmp_path) == "existing-probe"
    assert called == [tmp_path]
