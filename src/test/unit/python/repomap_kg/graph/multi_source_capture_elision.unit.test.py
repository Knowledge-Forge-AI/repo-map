def _graph(tmp_path: Path, *, polyglot: bool = False) -> OpsGraphConfig:
    bindings = []
    for alias, role in (("entry", "entry"), ("support", "dependency")):
        root = tmp_path / alias
        root.mkdir()
        (root / "module.py").write_text("def greet():\n    return 'hello'\n", encoding="utf-8")
        (root / "README.md").write_text("# Héllo\nA shared 🐦 document.\n", encoding="utf-8")
        if polyglot:
            (root / "empty.txt").write_bytes(b"")
            script = root / "run"
            script.write_text("#!/bin/bash\nprintf '%s\\n' hello\n", encoding="utf-8")
            script.chmod(0o700)
            (root / "generated.go").write_text(
                "// Code generated by fixture. DO NOT EDIT.\npackage fixture\n", encoding="utf-8",
            )
            (root / "flake.nix").write_text("{ outputs = _: { answer = 42; }; }\n", encoding="utf-8")
        bindings.append(replace(make_test_binding("elision", alias, root, role), repository_name="equivalence"))
    return OpsGraphConfig(
        id="elision", name="Elision fixture", root_path="", root_path_expanded="",
        repository_name="equivalence", privacy="public-dev", enabled=True, mcp_visible=False,
        extractor_profile="default", refresh_policy="manual", source_bindings=tuple(bindings),
        explicit_source_bindings=True,
    )


def _sealed(graph: OpsGraphConfig) -> tuple[SealedSourceBinding, ...]:
    return tuple(
        SealedSourceBinding(
            binding_id=b.binding_id, source_definition_id=b.source_definition_id,
            alias=b.alias, revision=b.revision, source_kind=b.source_kind,
            root=Path(b.root_path_expanded), repository_scope=b.repository_name or "",
            logical_root=b.logical_root or "", privacy=b.privacy,
            evidence_retention=b.evidence_retention or "", extractor_profile=b.extractor_profile or "",
            selection_policy_id=b.selection_policy_id, resolution_policy=b.resolution_policy or "",
            role=b.role, input_name=b.input_name,
        )
        for b in graph.effective_source_bindings
    )


def _witness(monkeypatch: pytest.MonkeyPatch) -> tuple[list[Path], list[tuple[Path, str, int]]]:
    hashes: list[Path] = []
    stable: list[tuple[Path, str, int]] = []
    original_hash = _discovery_classify.content_hash
    original_stable = multi_source_capture._read_stable_file

    def discovery_hash(path: Path) -> str:
        value = original_hash(path)
        hashes.append(path)
        return value

    def stable_read(path: Path, *, stage_path: Path | None = None) -> tuple[str, int, bool]:
        value = original_stable(path, stage_path=stage_path)
        stable.append((path, value[0], value[1]))
        return value

    monkeypatch.setattr(_discovery_classify, "content_hash", discovery_hash)
    monkeypatch.setattr(multi_source_capture, "_read_stable_file", stable_read)
    return hashes, stable


def test_sealed_capture_elides_discarded_discovery_reads(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    graph = _graph(tmp_path)
    reference = capture_multi_source_candidate(graph)
    hashes, stable = _witness(monkeypatch)
    actual = capture_sealed_multi_source_candidate(
        graph.id, _sealed(graph), expected_snapshot_vector=reference.candidate.snapshot_vector,
    )
    assert actual == reference
    assert hashes == []
    assert len(stable) == 8  # two authoritative passes over four real files
    assert all(digest == hashlib.sha256(path.read_bytes()).hexdigest() for path, digest, _ in stable)
    assert sum(size for _, _, size in stable) == 2 * sum(
        path.stat().st_size for binding in graph.effective_source_bindings
        for path in Path(binding.root_path_expanded).iterdir()
    )


def test_default_capture_keeps_discovery_hashes(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    graph = _graph(tmp_path)
    hashes, stable = _witness(monkeypatch)
    actual = capture_multi_source_candidate(graph)
    assert len(hashes) == len(stable) == 8
    assert len(actual.candidate.snapshot_vector) == 2


@pytest.mark.parametrize("polyglot", [False, True])
def test_sealed_capture_keeps_semantics_and_family_checksums(tmp_path: Path, polyglot: bool) -> None:
    graph = _graph(tmp_path, polyglot=polyglot)
    reference = capture_multi_source_candidate(graph)
    actual = capture_sealed_multi_source_candidate(
        graph.id, _sealed(graph), expected_snapshot_vector=reference.candidate.snapshot_vector,
    )
    assert actual == reference
    expected_rows = build_staged_rows(reference.observations, repository_name="equivalence", stage_id="stage-unassigned")
    actual_rows = build_staged_rows(actual.observations, repository_name="equivalence", stage_id="stage-unassigned")
    try:
        assert actual_rows.checksums == expected_rows.checksums
        assert actual_rows.row_counts == expected_rows.row_counts
        assert {name: tuple(rows) for name, rows in actual_rows.family_rows.items()} == {
            name: tuple(rows) for name, rows in expected_rows.family_rows.items()
        }
    finally:
        actual_rows.close()
        expected_rows.close()


def test_sealed_capture_still_refuses_a_different_snapshot_vector(tmp_path: Path) -> None:
    graph = _graph(tmp_path)
    reference = capture_multi_source_candidate(graph)
    vector = reference.candidate.snapshot_vector
    wrong = ((vector[0][0], vector[0][1] + 1, vector[0][2]), *vector[1:])
    with pytest.raises(MultiSourceCaptureError) as error:
        capture_sealed_multi_source_candidate(graph.id, _sealed(graph), expected_snapshot_vector=wrong)
    assert error.value.category == "source_changed"


def test_hooked_discovery_keeps_nested_symlink_and_restricted_directory_selection(tmp_path: Path) -> None:
    (tmp_path / "root.py").write_text("value = 1\n", encoding="utf-8")
    nested = tmp_path / "nested"
    nested.mkdir()
    (nested / "README.md").write_text("# Nested public input\n", encoding="utf-8")
    (tmp_path / "directory-alias").symlink_to(nested, target_is_directory=True)
    excluded = tmp_path / "node_modules"
    excluded.mkdir()
    (excluded / "ignored.py").write_text("ignored = True\n", encoding="utf-8")
    restricted = tmp_path / "restricted"
    restricted.mkdir()
    (restricted / "private-mode.txt").write_bytes(b"public fixture")
    restricted.chmod(0)
    try:
        ordinary = discover_repository(tmp_path)
        hooked = discover_repository(tmp_path, io_hooks=CaptureDiscoveryHooks())
        by_path = {item.path: item for item in ordinary}
        assert [replace(item, content_hash=by_path[item.path].content_hash) for item in hooked] == ordinary
        assert all("directory-alias/" not in str(item.path) and "node_modules/" not in str(item.path) for item in hooked)
    finally:
        restricted.chmod(0o700)
